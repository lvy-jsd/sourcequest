export class CapabilityRegistry implements CapabilityRegistryPort {
  private readonly entries = new Map<string, CapabilityEntry>();
  private revision = 1;

  constructor(initial: readonly CapabilityEntry[] = DEFAULT_CAPABILITIES) {
    for (const entry of initial) {
      this.entries.set(entry.id, { ...entry });
    }
  }

  register(entry: CapabilityEntry): void {
    this.entries.set(entry.id, { ...entry });
    this.revision += 1;
  }

  list(kind?: CapabilityEntry["kind"]): readonly CapabilityEntry[] {
    const all = [...this.entries.values()].map((e) => ({ ...e }));
    return kind ? all.filter((e) => e.kind === kind) : all;
  }

  get(id: string): CapabilityEntry | undefined {
    const found = this.entries.get(id);
    return found ? { ...found } : undefined;
  }

  setEnabled(id: string, enabled: boolean): void {
    const found = this.entries.get(id);
    if (!found) throw new Error(`Unknown capability: ${id}`);
    if (found.enabled !== enabled) {
      this.entries.set(id, { ...found, enabled });
      this.revision += 1;
    }
  }

  setCredentialConfigured(id: string, configured: boolean): void {
    const found = this.entries.get(id);
    if (!found) throw new Error(`Unknown capability: ${id}`);
    if (found.credentialConfigured !== configured) {
      this.entries.set(id, { ...found, credentialConfigured: configured });
      this.revision += 1;
    }
  }

  policyRevision(): string {
    return `pol-v${this.revision}`;
  }

  supportsAllFilters(id: string, constraints: SearchQueryConstraints | undefined): boolean {
    if (!constraints) return true;
    const found = this.entries.get(id);
    if (!found) return false;
    const required = (Object.keys(constraints) as (keyof SearchQueryConstraints)[]).filter(
      (k) => constraints[k] !== undefined && (!Array.isArray(constraints[k]) || constraints[k].length > 0),
    );
    return required.every((filter) => found.supportedFilters.includes(filter));
  }
}
